CREATE TABLE user_permissions (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  user_id BIGINT NOT NULL REFERENCES users(id),
                                  permission_id BIGINT NOT NULL REFERENCES permissions(id),
                                  effect VARCHAR(5) NOT NULL,

                                  assigned_at TIMESTAMPTZ NOT NULL,
                                  assigned_by VARCHAR(100) NOT NULL,
                                  expires_at TIMESTAMPTZ,
                                  revoked_at TIMESTAMPTZ,
                                  revoked_by VARCHAR(100),
                                  reason VARCHAR(255),

                                  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                                  deleted_at TIMESTAMPTZ,
                                  deleted_by VARCHAR(100),

                                  created_at TIMESTAMPTZ NOT NULL,
                                  created_by VARCHAR(100) NOT NULL,
                                  updated_at TIMESTAMPTZ NOT NULL,
                                  updated_by VARCHAR(100) NOT NULL,
                                  version BIGINT NOT NULL DEFAULT 0,

                                  CONSTRAINT ck_user_permissions_effect
                                      CHECK (effect IN ('GRANT', 'DENY')),

                                  CONSTRAINT ck_user_permissions_expiry
                                      CHECK (expires_at IS NULL OR expires_at > assigned_at),

                                  CONSTRAINT ck_user_permissions_revocation CHECK (
                                      (revoked_at IS NULL AND revoked_by IS NULL)
                                          OR (
                                          revoked_at IS NOT NULL
                                              AND revoked_by IS NOT NULL
                                              AND revoked_at >= assigned_at
                                          )
                                      )
);

CREATE UNIQUE INDEX uk_user_permissions_unrevoked
    ON user_permissions(user_id, permission_id)
    WHERE revoked_at IS NULL AND is_deleted = FALSE;

CREATE INDEX ix_user_permissions_permission
    ON user_permissions(permission_id);

