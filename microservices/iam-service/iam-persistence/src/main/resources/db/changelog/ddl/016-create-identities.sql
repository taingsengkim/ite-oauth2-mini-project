CREATE TABLE identities (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            uuid UUID NOT NULL UNIQUE,

                            user_id BIGINT NOT NULL REFERENCES users(id),
                            provider VARCHAR(20) NOT NULL,
                            provider_subject VARCHAR(255) NOT NULL,

                            email VARCHAR(255),
                            email_verified BOOLEAN NOT NULL DEFAULT FALSE,
                            display_name VARCHAR(150),
                            username VARCHAR(100),
                            picture_url VARCHAR(500),
                            attributes JSONB,

                            linked_at TIMESTAMPTZ NOT NULL,
                            last_login_at TIMESTAMPTZ,

                            is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                            deleted_at TIMESTAMPTZ,
                            deleted_by VARCHAR(100),

                            created_at TIMESTAMPTZ NOT NULL,
                            created_by VARCHAR(100) NOT NULL,
                            updated_at TIMESTAMPTZ NOT NULL,
                            updated_by VARCHAR(100) NOT NULL,
                            version BIGINT NOT NULL DEFAULT 0,

                            CONSTRAINT ck_identities_provider CHECK (
                                provider IN ('GOOGLE', 'GITHUB', 'FACEBOOK', 'TELEGRAM')
                                ),

                            CONSTRAINT ck_identities_subject CHECK (
                                LENGTH(TRIM(provider_subject)) > 0
                                ),

                            CONSTRAINT ck_identities_verified_email CHECK (
                                NOT email_verified
                                    OR (email IS NOT NULL AND LENGTH(TRIM(email)) > 0)
                                ),

                            CONSTRAINT ck_identities_deletion CHECK (
                                (
                                    is_deleted = FALSE
                                        AND deleted_at IS NULL
                                        AND deleted_by IS NULL
                                    )
                                    OR (
                                    is_deleted = TRUE
                                        AND deleted_at IS NOT NULL
                                        AND deleted_by IS NOT NULL
                                    )
                                )
);

CREATE UNIQUE INDEX uk_identities_active_provider_subject
    ON identities(provider, provider_subject)
    WHERE is_deleted = FALSE;

CREATE UNIQUE INDEX uk_identities_active_user_provider
    ON identities(user_id, provider)
    WHERE is_deleted = FALSE;