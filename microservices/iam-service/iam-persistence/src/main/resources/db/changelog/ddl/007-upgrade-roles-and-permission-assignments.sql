CREATE TABLE role_perms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    permission_id BIGINT NOT NULL REFERENCES permissions(id),
    assigned_at TIMESTAMPTZ NOT NULL,
    assigned_by VARCHAR(100) NOT NULL,
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoked_by VARCHAR(100),
    reason VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    deleted_by VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_role_perms_expiry CHECK (expires_at IS NULL OR expires_at > assigned_at),
    CONSTRAINT ck_role_perms_revocation CHECK (
        (revoked_at IS NULL AND revoked_by IS NULL)
        OR (revoked_at >= assigned_at AND revoked_by IS NOT NULL))
);
CREATE UNIQUE INDEX uk_role_perms_unrevoked
    ON role_perms(role_id, permission_id) WHERE revoked_at IS NULL AND is_deleted = FALSE;
CREATE INDEX ix_role_perms_permission ON role_perms(permission_id);
